export type Label = keyof typeof labels;
export const translate = (lang: Language, key: Label) =>
  labels[key][lang === "ar" ? 1 : 0];
export function errorLabel(e: unknown): Label {
  const x = String((e as { message?: string })?.message || e);
  if (x.includes("23505") || x.includes("duplicate key")) return "duplicate";
  if (x.includes("42501") || x.includes("permission denied"))
    return "forbidden";
  const k = Object.keys(labels).find((k) => x.includes(k));
  return (k || "request_failed") as Label;
}
